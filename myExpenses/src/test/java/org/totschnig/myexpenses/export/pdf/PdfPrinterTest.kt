/**
 * Pins which file is written, and which transactions and fields end up in it.
 */
@RunWith(AndroidJUnit4::class)
class PdfPrinterTest : BasePdfTest() {

    private val accountId by lazy { insertAccount("Cash") }
    private val account by lazy { pageAccount(accountId) }
    private val payee by lazy { repository.requireParty("Alice")!! }

    private val defaultLocale: Locale = Locale.getDefault()

    @After
    fun restoreLocale() {
        Locale.setDefault(defaultLocale)
    }

    // File

    @Test
    fun fileIsNamedAfterTheAccountWithATimestamp() {
        val id = insertAccount("My Account #1")
        book(id)
        val pdf = print(pageAccount(id, "My Account #1"))
        // On a device the regular expression also keeps letters outside of ASCII, here it does not.
        assertThat(pdf.file.name).matches("""MyAccount1-\d{8}-\d{6}\.pdf""")
        assertThat(pdf.file.length()).isGreaterThan(0L)
        assertThat(pdf.uri.scheme).isEqualTo("file")
    }

    @Test
    fun resultIsTheUriAndForAFileTheAbsolutePath() {
        book(accountId)
        val pdf = print(account)
        assertThat(pdf.displayName).isEqualTo(pdf.file.absolutePath)
        assertThat(pdf.uri.path).isEqualTo(pdf.file.absolutePath)
    }

    @Test
    fun documentHasTitleAndSubject() {
        book(accountId)
        val info = print(account).info
        assertThat(info["Title"]).isEqualTo("Cash")
        assertThat(info["Subject"]).isEqualTo("Generated by MyExpenses.mobi")
    }

    // Failures

    @Test
    fun emptyAccountFailsAndLeavesAnEmptyFileBehind() {
        val dest = newDestDir()
        val exception = assertThrows(IllegalStateException::class.java) {
            PdfPrinter.print(application, account, dest, null, ColorSource.TYPE)
        }
        assertThat(exception).hasMessageThat().isEqualTo("No data")
        // Looks like a bug: the file is created before the query, and it is not removed. The
        // message is also not translated, and it reaches the user.
        assertThat(dest.listFiles().map { it.length() }).containsExactly(0L)
    }

    @Test
    fun otherAccountsDoNotCount() {
        book(insertAccount("Other"))
        assertThrows(IllegalStateException::class.java) { print(account) }
    }

    @Test
    fun filterWithoutMatchFailsLikeAnEmptyAccount() {
        book(accountId)
        val exception = assertThrows(IllegalStateException::class.java) {
            print(account, CategoryCriterion("Bakery", writeCategory("Bakery")))
        }
        assertThat(exception).hasMessageThat().isEqualTo("No data")
    }

    @Test
    fun layoutWithoutFieldsFailsAndLeavesADocumentBehind() {
        book(accountId)
        prefHandler.printLayout = emptyList()
        val dest = newDestDir()
        val exception = assertThrows(IllegalStateException::class.java) {
            PdfPrinter.print(application, account, dest, null, ColorSource.TYPE)
        }
        assertThat(exception).hasMessageThat()
            .isEqualTo("Please add at least one field to be printed.")
        // Looks like a bug: unlike the layout, the document is not checked before it is opened.
        assertThat(dest.listFiles().single().length()).isGreaterThan(0L)
    }

    @Test
    fun layoutWithOnlyTheDateFailsWhenTheDateIsDropped() {
        book(accountId)
        useLayout(listOf(Date))
        prefHandler.putBoolean(PrefKey.TRANSACTION_WITH_TIME, false)
        assertThrows(IllegalStateException::class.java) {
            print(account.copy(grouping = Grouping.DAY))
        }
    }

    @Test
    fun widthsThatDoNotMatchTheColumnsFailThePrint() {
        book(accountId)
        useLayout(listOf(Date), listOf(Amount), widths = listOf(100, 100, 100))
        // Looks like a bug: the layout screen resets such widths when it loads them, the print
        // does not. Saving through the screen keeps the two lists in step.
        assertThrows(DocumentException::class.java) { print(account) }
    }

    // Header of the document

    @Test
    fun headerShowsLabelAndTheBalanceOfThePassedAccount() {
        book(accountId)
        val pdf = print(account.copy(label = "Pocket", currentBalance = 12345))
        assertThat(pdf.texts).containsAtLeast("Pocket", "Current balance : ", "€123.45").inOrder()
    }

    @Test
    fun balanceIsColouredBySign() {
        book(accountId)
        val colorOf = { balance: Long, text: String ->
            print(account.copy(currentBalance = balance)).pieces
                .first { text in it.text }.color?.rgb
        }
        assertThat(colorOf(100, "€1.00")).isEqualTo(INCOME_COLOR)
        assertThat(colorOf(-100, "€1.00")).isEqualTo(EXPENSE_COLOR)
        assertThat(colorOf(0, "Current balance : €0.00")).isNull()
    }

    @Test
    fun filterIsPrintedBelowTheBalance() {
        val bakery = writeCategory("Bakery")
        book(accountId, categoryId = bakery)
        val pdf = print(account.copy(currentBalance = 100), CategoryCriterion("Bakery", bakery))
        assertThat(pdf.texts).containsAtLeast("Current balance : ", "€1.00", "Bakery").inOrder()
    }

    // Layout

    @Test
    fun defaultLayoutPrintsAllFieldsOfATransactionInFourColumns() {
        val food = writeCategory("Food")
        val bakery = writeCategory("Bakery", food)
        val id = book(accountId, -500, bakery, payee, "Rolls", "R12")
        repository.saveTagsForTransaction(
            listOf(repository.writeTag("T1"), repository.writeTag("T2")),
            id
        )
        val pdf = print(account)
        val columns = listOf("Date", "Account", "Payee", "Original").map { pdf.piece(it).x }
        val columnOf = { text: String -> pdf.columnOf(text, columns) }
        assertThat(columnOf("3/15/25")).isEqualTo(0)
        assertThat(columnOf("Food > Bakery")).isEqualTo(1)
        assertThat(columnOf("T1, T2")).isEqualTo(1)
        assertThat(columnOf("Alice")).isEqualTo(2)
        assertThat(columnOf("R12 / Rolls")).isEqualTo(2)
        assertThat(pdf.piece("€5.00").endX).isWithin(0.1f).of(pdf.piece("Amount").endX)
    }

    @Test
    fun titlesOfTheDefaultLayout() {
        book(accountId)
        assertThat(print(account).texts).containsAtLeast(
            "Date",
            "Account",
            "Category",
            "Tags",
            "Payee",
            "Reference Number / Notes",
            "Original",
            "amount",
            "Amount"
        ).inOrder()
    }

    @Test
    fun fieldsOutsideOfTheLayoutAreNotPrinted() {
        book(accountId, -500, writeCategory("Bakery"), payee, "Rolls", "R12")
        useLayout(listOf(Date), listOf(Amount))
        val texts = print(account).texts
        assertThat(texts).containsAtLeast("3/15/25", "€5.00")
        assertThat(texts).containsNoneOf("Bakery", "Alice", "Rolls", "R12", "Category", "Payee")
    }

    @Test
    fun orderInsideOfAColumnFollowsTheLayout() {
        book(accountId, comment = "Rolls", referenceNumber = "R12", payeeId = payee)
        useLayout(listOf(Notes, Payee, ReferenceNumber))
        assertThat(print(account).texts).containsAtLeast("Rolls", "Alice", "R12").inOrder()
    }

    @Test
    fun combinedFieldJoinsWhatIsThereWithASlash() {
        useLayout(listOf(CombinedField(listOf(Payee, Notes, ReferenceNumber))))
        book(accountId, payeeId = payee, comment = "Both", date = DATE)
        book(accountId, comment = "Single", date = DATE.minusDays(1))
        val texts = print(account).texts
        assertThat(texts).containsAtLeast(
            "Payee / Notes / Reference Number",
            "Alice / Both",
            "Single"
        ).inOrder()
    }

    @Test
    fun emptyFieldsLeaveNoLine() {
        book(accountId)
        useLayout(listOf(Category, Tags, Notes))
        assertThat(print(account).texts.last()).isEqualTo("Notes")
    }

    @Test
    fun columnsGetTheirShareOfTheConfiguredWidths() {
        book(accountId)
        useLayout(listOf(Date), listOf(Category), listOf(Amount), widths = listOf(100, 300, 100))
        val pdf = print(account)
        val left = PageSize.A4.width * 0.06f
        val width = PageSize.A4.width - 2 * left
        val padding = 5f
        assertThat(pdf.piece("Date").x).isWithin(0.5f).of(left + padding)
        assertThat(pdf.piece("Category").x).isWithin(0.5f).of(left + width * 0.2f + padding)
        assertThat(pdf.piece("Amount").endX).isWithin(0.5f).of(left + width - padding)
    }

    @Test
    fun columnsOfOnlyAmountsAreRightAlignedOthersLeft() {
        book(accountId, comment = "Rolls")
        useLayout(listOf(Amount, Notes), listOf(Amount), widths = listOf(100, 100))
        val pdf = print(account)
        val middle = PageSize.A4.width / 2
        assertThat(pdf.pieces.first { it.text == "Amount" }.x).isLessThan(middle - 100)
        assertThat(pdf.pieces.last { it.text == "Amount" }.x).isGreaterThan(middle + 100)
        assertThat(pdf.pieces.last { it.text == "€5.00" }.endX)
            .isWithin(0.5f).of(PageSize.A4.width * 0.94f - 5f)
    }

    @Test
    fun rightToLeftLocaleMirrorsColumnsButTogglesTheWidthsPerGroup() {
        Locale.setDefault(Locale.forLanguageTag("he"))
        book(accountId, comment = "New", date = DATE)
        book(accountId, comment = "Old", date = DATE.minusMonths(1))
        useLayout(
            listOf(Notes),
            listOf(Payee),
            listOf(Amount),
            widths = listOf(100, 200, 700)
        )
        val pdf = print(account.copy(grouping = Grouping.MONTH))
        val notes = pdf.pieces.first { it.text == "Notes" }
        val amount = pdf.pieces.first { it.text == "Amount" }
        assertThat(notes.x).isGreaterThan(amount.x)
        val payees = pdf.pieces.filter { it.text == "Payee" }
        // Looks like a bug: columnWidths is reversed in place for each group, so the second group
        // has the widths the other way around and its columns do not line up with the first.
        assertThat(payees[1].x).isNotEqualTo(payees[0].x)
    }

    // Sorting

    @Test
    fun sortFollowsTheAccount() {
        book(accountId, comment = "Old", date = DATE.minusDays(2))
        book(accountId, comment = "New", date = DATE)
        useLayout(listOf(Notes))
        assertThat(print(account).texts).containsAtLeast("New", "Old").inOrder()
        assertThat(print(account.copy(sortDirection = SortDirection.ASC)).texts)
            .containsAtLeast("Old", "New").inOrder()
    }

    @Test
    fun sortByAmountIgnoresTheSign() {
        book(accountId, -300, comment = "Three")
        book(accountId, 200, comment = "Two")
        book(accountId, -100, comment = "One")
        useLayout(listOf(Notes))
        val sorted = account.copy(sortBy = KEY_AMOUNT, sortDirection = SortDirection.ASC)
        assertThat(print(sorted).texts).containsAtLeast("One", "Two", "Three").inOrder()
    }

    // Kinds of transactions

    @Test
    fun transferShowsThePeerAccountAndTheTransferCategory() {
        repository.insertTransfer(
            accountId,
            insertAccount("Giro"),
            -250,
            date = DATE,
            comment = "Move"
        )
        val pdf = print(account)
        // The arrow in front of the label is lost in Helvetica, see BasePdfTest.
        assertThat(pdf.texts).containsAtLeast(" Giro", "Transfer", "Move", "€2.50").inOrder()
    }

    @Test
    fun accountFieldOfANormalTransactionInARealAccountIsEmpty() {
        book(accountId)
        useLayout(listOf(Account), listOf(Amount))
        assertThat(print(account).texts.count { it == "Cash" }).isEqualTo(1)
    }

    @Test
    fun splitPrintsTheParentAndThenItsPartsWithoutDateAndPayee() {
        val first = writeCategory("First")
        val second = writeCategory("Second")
        insertSplit(accountId, payee, listOf(first, second))
        val pdf = print(account)
        assertThat(pdf.texts).containsAtLeast(
            "3/15/25",
            "Alice",
            "€6.00",
            "Second",
            "Part 1",
            "€3.00",
            "First",
            "Part 0",
            "€3.00"
        ).inOrder()
        assertThat(pdf.texts.count { it == "3/15/25" }).isEqualTo(1)
        assertThat(pdf.texts.count { it == "Alice" }).isEqualTo(1)
    }

    @Test
    fun partsOfASplitAreNotPrintedAsTheirOwnRows() {
        insertSplit(accountId, payee, listOf(writeCategory("First")))
        assertThat(print(account).texts.count { it == "Part 0" }).isEqualTo(1)
    }

    @Test
    fun voidedTransactionIsPrintedWithALineThrough() {
        book(accountId, comment = "Voided", crStatus = CrStatus.VOID)
        val pdf = print(account)
        assertThat(pdf.texts).contains("Voided")
        assertThat(pdf.hasRedLine).isTrue()
    }

    @Test
    fun otherTransactionsHaveNoLineThrough() {
        book(accountId, crStatus = CrStatus.RECONCILED)
        book(accountId, crStatus = CrStatus.CLEARED)
        assertThat(print(account).hasRedLine).isFalse()
    }

    @Test
    fun voidedTransactionHasNoLineWhenNoCellHoldsJustOneField() {
        book(
            accountId,
            categoryId = writeCategory("Bakery"),
            payeeId = payee,
            comment = "Voided",
            crStatus = CrStatus.VOID
        )
        useLayout(listOf(Payee, Category), listOf(Notes, Amount))
        val pdf = print(account)
        assertThat(pdf.texts).contains("Voided")
        // Looks like a bug: the mark for the line is put on the phrase of the cell, and cells with
        // more than one line hold a nested table instead.
        assertThat(pdf.hasRedLine).isFalse()
    }

    @Test
    fun archiveIsOneRowWithItsPeriodAndItsContentIsLeftOut() {
        book(accountId, comment = "Inside", date = LocalDateTime.of(2025, 2, 10, 9, 0))
        book(accountId, comment = "Outside", date = DATE)
        repository.archive(accountId, LocalDate.of(2025, 2, 1) to LocalDate.of(2025, 2, 28))
        val texts = print(account).texts
        assertThat(texts).containsAtLeast("Outside", "Feb 1, 2025 - Feb 28, 2025")
        assertThat(texts).doesNotContain("Inside")
    }

    // Date column

    private fun dateColumn(grouping: Grouping): List<String> {
        book(accountId, comment = "Row")
        useLayout(listOf(Date), listOf(Notes))
        val pdf = print(account.copy(grouping = grouping))
        val rowY = pdf.piece("Row").y
        return pdf.pieces.filter { it.y == rowY && it.text != "Row" }.map { it.text }
    }

    @Test
    fun withoutGroupingTheDateHasAShortYear() {
        assertThat(dateColumn(Grouping.NONE)).containsExactly("3/15/25")
    }

    @Test
    fun inAMonthGroupOnlyTheDayIsPrinted() {
        assertThat(dateColumn(Grouping.MONTH)).containsExactly("15")
    }

    @Test
    fun inAMonthGroupWithAnotherStartDayMonthAndDayArePrinted() {
        // Changing this preference schedules work.
        WorkManagerTestInitHelper.initializeTestWorkManager(application)
        prefHandler.putString(PrefKey.GROUP_MONTH_STARTS, "10")
        assertThat(dateColumn(Grouping.MONTH)).containsExactly("3/15")
    }

    @Test
    fun inAWeekGroupTheWeekdayIsPrinted() {
        assertThat(dateColumn(Grouping.WEEK)).containsExactly("Sat")
    }

    @Test
    fun inAYearGroupMonthAndDayArePrinted() {
        assertThat(dateColumn(Grouping.YEAR)).containsExactly("3/15")
    }

    @Test
    fun inADayGroupTheTimeIsPrintedInAColumnCalledTime() {
        assertThat(dateColumn(Grouping.DAY)).containsExactly("10:30 AM")
        assertThat(print(account.copy(grouping = Grouping.DAY)).texts).contains("Time")
    }

    @Test
    fun inADayGroupWithoutTimesTheDateFieldIsDroppedWithItsWidth() {
        book(accountId, comment = "Row", payeeId = payee)
        prefHandler.putBoolean(PrefKey.TRANSACTION_WITH_TIME, false)
        useLayout(
            listOf(Date),
            listOf(Payee, Date),
            listOf(Notes),
            widths = listOf(900, 100, 300)
        )
        val pdf = print(account.copy(grouping = Grouping.DAY))
        assertThat(pdf.texts).containsNoneOf("Date", "Time", "10:30 AM")
        val left = PageSize.A4.width * 0.06f
        val width = PageSize.A4.width - 2 * left
        assertThat(pdf.piece("Alice").x).isWithin(0.5f).of(left + 5f)
        assertThat(pdf.piece("Row").x).isWithin(0.5f).of(left + width * 0.25f + 5f)
    }

    @Test
    fun theDateIsTheBookingDateAndFollowsTheLocalTime() {
        book(accountId, date = LocalDateTime.of(2025, 12, 31, 23, 59))
        assertThat(print(account).texts).contains("12/31/25")
    }
}
